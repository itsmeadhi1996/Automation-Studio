test('shared preconditions survive saves and become independent manual and automation snapshots',()=>{
 const counter={nextTestNumber:1},raw=sampleProject(3200);
 raw.prerequisites=[{id:'setup',name:'Sign in',steps:[{name:'Open sign-in',action:'navigate',value:'https://example.test'}],qa:{description:'Use a test account',manualSteps:[{id:'setup-step',instruction:'Sign in with valid credentials',expectedResult:'Dashboard appears'}]}}];
 raw.tests[0].prerequisiteId='setup';raw.tests[0].inTestPlan=true;
 let p=normalizeProject(raw,null,counter);
 const manual=createManualRun(p,{testId:'welcome'}),automated=prepareRun(p,{testId:'welcome'});
 assert.equal(manual.tests[0].steps[0].name,'Sign in / Sign in with valid credentials');
 assert.equal(manual.tests[0].steps[0].phase,'prerequisite');
 assert.equal(automated.tests[0].steps[0].action,'navigate');
 assert.equal(automated.tests[0].steps[0].prerequisiteId,'setup');
 const next=structuredClone(p);
 delete next.prerequisites[0].qa;
 p=normalizeProject(next,p,counter);
 assert.equal(p.prerequisites[0].qa.manualSteps[0].instruction,'Sign in with valid credentials');
 p.prerequisites[0].qa.manualSteps[0].instruction='Updated setup';
 assert.equal(manual.tests[0].steps[0].name,'Sign in / Sign in with valid credentials');
 assert.equal(automated.tests[0].steps[0].name,'Sign in / Open sign-in');
});

