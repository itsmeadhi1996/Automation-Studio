
import test from 'node:test';
import assert from 'node:assert/strict';
import path from 'node:path';
import {chromium} from 'playwright';
import {createStudio} from './support.mjs';
test('Automation test cases use QA-style folder filters, table pagination and editor navigation',{timeout:60000},async t=>{
 const storage=path.resolve('.test-output','automation-list-'+Date.now()),studio=await createStudio({port:3353,storage});await studio.listen();
 const browser=await chromium.launch();t.after(async()=>{await browser.close();await studio.close();});
 const base='http://127.0.0.1:3353';
 const response=await fetch(base+'/api/projects',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({name:'List view',folders:[{id:'parent',name:'Parent'},{id:'child',name:'Child',parentId:'parent'}],suites:[{id:'smoke',name:'Smoke'}],tests:Array.from({length:31},(_,i)=>({id:'case-'+i,name:'Case '+i,folderId:i<3?'child':null,suiteId:i<3?'smoke':null,steps:[{name:'Wait',action:'wait',value:'0'}],qa:{owner:i<3?'Alex':'',priority:i<3?'high':'medium'}}))})});
 assert.equal(response.status,201);const p=await response.json();
 const page=await browser.newPage(),errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(base+'/automation?projectId='+p.id+'&view=cases');
 await page.locator('.auto-cases-table').waitFor();
 assert.equal(await page.locator('.auto-cases-table tbody tr').count(),25);
 assert.equal(await page.locator('#main').getByRole('columnheader',{name:'ASSIGNEE'}).count(),1);
 const choice=page.locator('[data-case-select]').first();
 await choice.focus();await page.keyboard.press('Space');
 assert.equal(await choice.evaluate(node=>node===document.activeElement),true);
 assert.equal(await page.locator('#auto-cases-all').evaluate(node=>node.indeterminate),true);
 await page.locator('[data-action="cases-clear-selection"]').click();
 await page.getByRole('navigation',{name:'Test case pages'}).getByRole('button',{name:'Next',exact:true}).click();
 assert.equal(await page.locator('.auto-cases-table tbody tr').count(),6);
 await page.locator('#auto-cases-all').check();
 assert.equal(await page.locator('.auto-cases-bulk strong').innerText(),'6 cases selected');
 await page.locator('[data-action="cases-clear-selection"]').click();
 await page.locator('#auto-cases-search').fill('Alex');
 assert.equal(await page.locator('.auto-cases-table tbody tr').count(),3);
 await page.locator('[data-cases-filter="priority"]').selectOption('low');
 await page.getByRole('heading',{name:'No test cases found'}).waitFor();
 await page.locator('#auto-cases-results [data-action="cases-clear-filters"]').click();
 assert.equal(await page.locator('#auto-cases-search').evaluate(node=>node===document.activeElement),true);
 await page.locator('[data-action="cases-folder"][data-folder="parent"]').click();
 assert.equal(await page.locator('.auto-cases-table tbody tr').count(),3);
 await page.locator('[data-cases-filter="suite"]').selectOption('smoke');
 assert.equal(await page.locator('.auto-cases-table tbody tr').count(),3);
 await page.locator('.auto-case-link').first().click();
 await page.locator('.steps-table').waitFor();
 await page.locator('[data-step="0"][data-key="value"]').fill('15');
 await page.locator('.tabs [data-view="cases"]').click();
 await page.locator('.auto-case-link').first().click();
 assert.equal(await page.locator('[data-step="0"][data-key="value"]').inputValue(),'15');
 await page.locator('.tabs [data-view="cases"]').click();
 await page.locator('[data-action="cases-clear-filters"]').click();
 for(const width of [1365,390]){await page.setViewportSize({width,height:900});assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));}
 await page.setViewportSize({width:1365,height:900});await page.evaluate(()=>window.scrollTo(0,0));await page.screenshot({path:path.join(storage,'test-cases.png')});
 assert.deepEqual(errors,[]);
});
