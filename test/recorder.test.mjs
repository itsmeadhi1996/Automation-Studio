  assert.equal(saved.activeRecording, null);
  assert.ok(saved.projects[0].tests[0].steps.some(s => s.value === 'Recorder'));
  assert.equal(saved.projects[0].tests[0].steps.find(step=>step.action==='fill').name,'Enter text in the “Your name” text field — Enter your name in the welcome form');
  assert.equal(saved.projects[0].tests[0].steps.find(step=>step.action==='click').name,'Click the “Get started” button — Click Get started to submit the form');
