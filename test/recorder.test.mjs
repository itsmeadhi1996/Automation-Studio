test('each interaction is saved before stop and a restarted server recovers the draft', { timeout: 60000 }, async t => {
  const port = 3229, base = `http://127.0.0.1:${port}`;
  const storage = path.resolve('.test-output', `recording-recovery-${Date.now()}`);
  let session, studio;
  const options = { port, storage, recordingLauncher: async (...args) => {
    session = await startRecording(args[0],args[1],args[2],{...args[3],headless:true}); return session;
  } };
  studio = await createStudio(options); await studio.listen();
  t.after(async () => { await studio?.close(); });
  const request = async (route, data) => {
    const response = await fetch(base+route, { method: data ? 'POST' : 'GET', headers: { 'Content-Type': 'application/json' }, body: data ? JSON.stringify(data) : undefined });
    assert.equal(response.ok, true); return response.json();
  };
  const initial = await request('/api/state');
  await request('/api/recordings', { projectId: initial.projects[0].id, testId: initial.projects[0].tests[0].id, url: base+'/demo' });
  await session.page.getByLabel('Your name').fill('Persist immediately');
  await session.page.evaluate(() => window.__studioRecord({ action: 'barrier' }));
  await session.saveQueue;
  let disk = {recording:JSON.parse(await readFile(path.join(storage,'data','recording.json'),'utf8'))};
  assert.equal(disk.recording.status, 'recording');
  assert.ok(disk.recording.steps.some(s => s.value === 'Persist immediately'));
  assert.ok(session.summary().savedAt);
  assert.equal(session.summary().saving, false);
  await session.page.getByRole('button', { name: 'Get started' }).click();
  await session.page.evaluate(() => window.__studioRecord({ action: 'barrier' }));
  await session.saveQueue;
  disk = {recording:JSON.parse(await readFile(path.join(storage,'data','recording.json'),'utf8'))};
  assert.equal(disk.recording.steps.at(-1).action, 'click');
  const recorded = structuredClone(disk.recording.steps);
  await studio.close(); studio = null;
  studio = await createStudio(options); await studio.listen();
  const recovered = (await request('/api/state')).activeRecording;
  assert.equal(recovered.status, 'stopped');
  assert.deepEqual(recovered.steps, recorded);
  await request(`/api/recordings/${recovered.id}/discard`, {});
  await studio.close(); studio = null;
  studio = await createStudio(options); await studio.listen();
  assert.equal((await request('/api/state')).activeRecording, null);
});
