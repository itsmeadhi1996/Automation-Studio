test('QA mappings keep full instruction names, validate references, and preserve run snapshots', () => {
  const instruction = 'Verify the account details and expected greeting. '.repeat(5);
  const raw = sampleProject(3200), counter = {nextTestNumber:1};
  raw.tests[0].inTestPlan=true;
  raw.tests[0].qa = {manualSteps:[{id:'req-1',instruction}]};
  const original = structuredClone(raw.tests[0].steps);
  raw.tests[0].steps = mapRecordedSteps(original, raw.tests[0].qa.manualSteps, [
    {stepIndex:1,qaRequirementId:'req-1'}, {stepIndex:2,qaRequirementId:'req-1'}
  ]);
  let project = normalizeProject(raw,null,counter);
  assert.equal(project.tests[0].steps[1].name,instruction);
  assert.equal(project.tests[0].steps[2].name,instruction);
  const run = prepareRun(project,{testId:project.tests[0].id});
  assert.equal(run.tests[0].steps[1].qaRequirementId,'req-1');
  const next = structuredClone(project);
  next.tests[0].qa.manualSteps[0].instruction = 'Updated QA instruction';
  project = normalizeProject(next,project,counter);
  assert.equal(project.tests[0].steps[1].name,'Updated QA instruction');
  assert.equal(run.tests[0].steps[1].name,instruction);
  const unmapped = mapRecordedSteps(project.tests[0].steps,project.tests[0].qa.manualSteps,[{stepIndex:1,qaRequirementId:null}]);
  assert.equal(unmapped[1].name,original[1].name);
  assert.equal(unmapped[1].qaRequirementId,undefined);
  assert.throws(()=>mapRecordedSteps(original,[],[{stepIndex:0,qaRequirementId:'other-case'}]),/linked QA Studio/);
  assert.throws(()=>mapRecordedSteps(original,[],[{stepIndex:999,qaRequirementId:null}]),/Recorded step/);
  assert.throws(()=>mapRecordedSteps(original,[],[null]),/Recorded step/);
  assert.throws(()=>mapRecordedSteps(original,[],[{stepIndex:0,qaRequirementId:null},{stepIndex:0,qaRequirementId:null}]),/Duplicate/);
  const removed = structuredClone(project);
  removed.tests[0].qa.manualSteps=[];
  assert.equal(normalizeProject(removed,project,counter).tests[0].steps[1].name,original[1].name);
});

test('verification feedback and QA mappings work through review, restart and import', {timeout:60000}, async t => {
  const port=3264, base='http://127.0.0.1:'+port;
  const storage=path.resolve('.test-output','recorder-requirements-'+Date.now());
  let session,studio,browser;
  const setup={port,storage,recordingLauncher:async(...args)=>{session=await startRecording(args[0],args[1],args[2],{...args[3],headless:true});return session;}};
  studio=await createStudio(setup);await studio.listen();
  t.after(async()=>{await browser?.close();await studio?.close();});
  const api=async(route,method='GET',data)=>{
    const response=await fetch(base+route,{method,headers:{'Content-Type':'application/json'},body:data===undefined?undefined:JSON.stringify(data)});
    const body=await response.json();assert.equal(response.ok,true,JSON.stringify(body));return body;
  };
  let project=(await api('/api/state')).projects[0];
  const instruction='Confirm that the entered display name is preserved and the expected welcome greeting is visible to the user after submitting the form. <QA requirement>';
  project.tests[0].qa={manualSteps:[{id:'req-name',instruction},{id:'req-visible',instruction:'The form is visible'}]};
  project=await api('/api/projects/'+project.id,'PUT',project);
  browser=await launchBrowser('chrome');
  const ui=await browser.newPage({viewport:{width:1440,height:1000}}),errors=[];
  ui.on('pageerror',e=>errors.push(e.message));
  await ui.goto(base+'/automation');
  await ui.getByRole('button',{name:'Record Web',exact:true}).click();
  await ui.getByRole('button',{name:'Start recording',exact:true}).click();
  await ui.getByRole('button',{name:'Stop and review'}).waitFor();
  const target=session.page;
  await target.getByLabel('Your name').fill('Alex');
  await target.getByRole('button',{name:'Get started'}).click();
  // Inspection modes are chosen in the recording browser's toolbox; the Studio page has no mode picker.
  assert.equal(await ui.locator('#record-mode').count(),0);
  const modeNames={text:'Verify text',value:'Verify value',visible:'Verify visible'};
  const setMode=async mode=>{
    await target.locator('qa-studio-recorder-toolbox').getByRole('button',{name:modeNames[mode],exact:true}).click();
    await target.waitForFunction(value=>window.__studioRecorderMode===value,mode);
  };
  await setMode('text');
  await target.locator('#message').hover();
  assert.equal(await target.locator('[data-capture-highlight]').evaluate(el=>getComputedStyle(el).borderTopColor),'rgb(229, 72, 77)');
  await target.locator('#message').click();
  await target.getByRole('status').filter({hasText:'Text captured successfully'}).waitFor();
  assert.equal(session.steps.at(-1).action,'text');
  assert.equal(session.steps.at(-1).value,'Welcome, Alex!');
  const textCapture = session.steps.at(-1).captureScreenshot;
  assert.match(textCapture,/^capture-[\w-]+\.png$/);
  const imageResponse = await fetch(base+'/artifacts/'+textCapture);
  assert.equal(imageResponse.status,200);
  assert.equal(Buffer.from(await imageResponse.arrayBuffer()).subarray(1,4).toString(),'PNG');
  await setMode('value');
  await target.getByLabel('Your name').click();
  await target.getByRole('status').filter({hasText:'Field value captured successfully'}).waitFor();
  assert.equal(session.steps.at(-1).value,'Alex');
  await target.locator('#message').click();
  await target.getByRole('status').filter({hasText:'Select an input'}).waitFor();
  assert.equal(session.steps.at(-1).action,'value');
  await setMode('visible');
  await target.getByRole('button',{name:'Get started'}).click();
  await target.getByRole('status').filter({hasText:'Visible element captured'}).waitFor();
  assert.equal(session.steps.at(-1).action,'visible');
  for (const step of session.steps.filter(step=>['text','value','visible'].includes(step.action))) assert.ok(step.captureScreenshot);
  assert.ok(session.steps.filter(step=>!['text','value','visible'].includes(step.action)).every(step=>!step.captureScreenshot));
  const count=session.steps.length;
  await ui.getByRole('button',{name:'Pause',exact:true}).click();
  await ui.getByRole('button',{name:'Resume',exact:true}).waitFor();
  await target.locator('#message').click();
  await target.getByRole('status').filter({hasText:'Recording is paused'}).waitFor();
  assert.equal(session.steps.length,count);
  const rejected=await fetch(base+'/api/recordings/'+session.id+'/mappings',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({mappings:[{stepIndex:0,qaRequirementId:'req-name'}]})});
  assert.equal(rejected.status,400);
  await ui.getByRole('button',{name:'Stop and review'}).click();
  await ui.getByRole('button',{name:'Replace test steps'}).waitFor();
  const valueIndex=session.steps.findIndex(s=>s.action==='value');
  const mappedName='Verify the value in the “Your name” text field — '+instruction;
  const evidence=session.steps[valueIndex].captureScreenshot;
  const preview=ui.locator('tbody tr').nth(valueIndex).getByRole('link',{name:/View captured screenshot/});
  await preview.waitFor();
  assert.equal(await preview.getAttribute('href'),'/artifacts/'+evidence);
  await ui.getByLabel('QA requirement for recorded step '+(valueIndex+1),{exact:true}).selectOption('req-name');
  await ui.getByText('Step mapped to QA Studio requirement.',{exact:true}).waitFor();
  assert.equal(session.steps[valueIndex].name,mappedName);
  assert.equal(await ui.locator('tbody tr').nth(valueIndex).locator('.recorded-step-name').innerText(),mappedName);
  await ui.reload();
  assert.equal(await ui.getByLabel('QA requirement for recorded step '+(valueIndex+1),{exact:true}).inputValue(),'req-name');
  await ui.goto('about:blank');
  await studio.close();studio=null;
  studio=await createStudio(setup);await studio.listen();
  const recovered=(await api('/api/state')).activeRecording;
  assert.equal(recovered.steps[valueIndex].qaRequirementId,'req-name');
  assert.equal(recovered.steps[valueIndex].captureScreenshot,evidence);
  await api('/api/recordings/'+recovered.id+'/mappings','POST',{mappings:[{stepIndex:0,qaRequirementId:'req-visible'}]});
  await ui.goto('about:blank');
  await studio.close();studio=null;
  studio=await createStudio(setup);await studio.listen();
  assert.equal((await api('/api/state')).activeRecording.steps[0].qaRequirementId,'req-visible');
  await ui.goto(base+'/automation');
  await ui.getByRole('button',{name:'Replace test steps'}).click();
  await ui.getByRole('button',{name:'Replay',exact:true}).waitFor();
  assert.equal(await ui.getByLabel('Step '+(valueIndex+1)+' name',{exact:true}).inputValue(),mappedName);
  assert.equal(await ui.getByLabel('Step '+(valueIndex+1)+' name',{exact:true}).getAttribute('readonly'),'');
  let saved=(await api('/api/state')).projects[0];
  assert.equal(saved.tests[0].steps[valueIndex].qaRequirementId,'req-name');
  assert.equal(saved.tests[0].steps[valueIndex].captureScreenshot,evidence);
  await ui.locator('[data-row="'+valueIndex+'"]').getByRole('link',{name:/View captured screenshot/}).waitFor();
  await api('/api/history/retain','POST',{keep:1});
  assert.equal((await fetch(base+'/artifacts/'+evidence)).status,200);
  await ui.getByLabel('QA requirement for step '+(valueIndex+1),{exact:true}).selectOption('');
  await ui.locator('#save-button').click();
  await ui.waitForFunction(()=>document.querySelector('#save-status').textContent.includes('All changes saved'));
  saved=(await api('/api/state')).projects[0];
  assert.equal(saved.tests[0].steps[valueIndex].qaRequirementId,undefined);
  assert.notEqual(saved.tests[0].steps[valueIndex].name,instruction);
  assert.deepEqual(errors,[]);
});

